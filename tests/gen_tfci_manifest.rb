#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate a tfci command manifest from the tfc-workflows-tooling source.
#
# Usage: ruby tests/gen_tfci_manifest.rb <source_dir> <tag> > tests/tfci-<tag>-commands.txt
#
# Output, one line per command:   command<TAB>flag,flag,...
# Then one line for global flags: global<TAB>flag,flag,...
#
# How tfci parses its arguments (cli.go, main package):
#   1. flag.CommandLine.Parse(os.Args[1:]) parses the global flags. These are
#      the flag.String/flag.Bool calls in package main (hostname, token,
#      organization). They must come BEFORE the command.
#   2. The remaining args go to mitchellh/cli, which picks the command
#      ("run create") and hands the rest to the command's own FlagSet.
#      Every command FlagSet is built by Meta.flagSet() in meta.go, which adds
#      "json". So --json is a per-command flag and must come AFTER the command.

SOURCE_URL = 'https://github.com/hashicorp/tfc-workflows-tooling'

def die(msg)
  warn "gen_tfci_manifest: #{msg}"
  exit 2
end

die('usage: gen_tfci_manifest.rb <source_dir> <tag>') unless ARGV.size == 2
src, tag = ARGV
cli_go = File.join(src, 'cli.go')
cmd_dir = File.join(src, 'internal', 'command')
die("#{cli_go} not found") unless File.file?(cli_go)
die("#{cmd_dir} not found") unless File.directory?(cmd_dir)

# Flag names registered on a FlagSet variable named `f`:
#   f.StringVar(&c.X, "name", ...), f.BoolVar(...), f.Var((*T)(&c.X), "name", ...)
FLAGSET_RE = /\bf\.\w*Var\(.*?,\s*"([A-Za-z0-9_\-]+)"/.freeze
# Global flags in package main: flag.String("name", ...), flag.StringVar(&x, "name", ...)
GLOBAL_RE = /\bflag\.(?:String|Bool|Int|Int64|Uint|Duration|Float64)\(\s*"([A-Za-z0-9_\-]+)"/.freeze
GLOBAL_VAR_RE = /\bflag\.\w*Var\(.*?,\s*"([A-Za-z0-9_\-]+)"/.freeze

go_files = Dir.glob(File.join(cmd_dir, '*.go')).reject { |p| p.end_with?('_test.go') }.sort

# Flags that Meta.flagSet() adds to every command FlagSet.
meta_src = File.read(File.join(cmd_dir, 'meta.go'))
meta_fn = meta_src[/func \(c \*Meta\) flagSet\(.*?\n\}/m] || die('Meta.flagSet not found in meta.go')
meta_flags = meta_fn.scan(FLAGSET_RE).flatten

# Commands map in cli.go: "run create": func() ... return &cmd.CreateRunCommand{...}
cli_src = File.read(cli_go)
commands = cli_src.scan(/"([a-z][a-z ]*)":\s*func\(\)\s*\(cli\.Command,\s*error\)\s*\{\s*return\s*&cmd\.(\w+)\{/m)
die('no commands found in cli.go') if commands.empty?

lines = commands.map do |name, struct|
  file = go_files.find { |p| File.read(p) =~ /^func \(\w+ \*#{struct}\) flags\(\)/ } ||
         go_files.find { |p| File.read(p) =~ /^type #{struct} struct/ } ||
         die("no file defines #{struct} (command #{name})")
  body = File.read(file)
  fn = body[/^func \(\w+ \*#{struct}\) flags\(\).*?\n\}/m] || die("#{struct}.flags() not found in #{file}")
  flags = fn.scan(FLAGSET_RE).flatten
  flags += meta_flags if fn.include?('c.flagSet(')
  [name, flags.uniq.sort]
end

globals = []
[cli_go, File.join(src, 'main.go')].each do |p|
  next unless File.file?(p)

  s = File.read(p)
  globals += s.scan(GLOBAL_RE).flatten
  globals += s.scan(GLOBAL_VAR_RE).flatten
end
globals = globals.uniq.sort

puts "# tfci command manifest. Generated by tests/gen_tfci_manifest.rb. Do not edit by hand."
puts "# source: #{SOURCE_URL}"
puts "# tag: #{tag}"
puts "# generated: #{Time.now.utc.strftime('%Y-%m-%d')}"
puts '# Commands and flags come from cli.go and each command\'s flags() in internal/command/.'
puts '# "json" is added to every command by Meta.flagSet (meta.go): it goes AFTER the command.'
puts '# "global" flags are parsed in cli.go before the command: they go BEFORE the command.'
lines.sort_by(&:first).each { |name, flags| puts "#{name}\t#{flags.join(',')}" }
puts "global\t#{globals.join(',')}"
